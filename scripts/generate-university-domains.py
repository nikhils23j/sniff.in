"""Regenerates supabase/migrations/*_v2_university_domains.sql from the Hipo university-domains-list (MIT).

  curl -sL -o /tmp/unis.json https://raw.githubusercontent.com/Hipo/university-domains-list/master/world_universities_and_domains.json
  python3 -I scripts/generate-university-domains.py /tmp/unis.json > new_migration.sql
"""
import json, re, sys

def q(s):
    return "'" + s.replace("'", "''") + "'" if s is not None else 'null'

data = json.load(open(sys.argv[1]))
seen = {}
for u in data:
    name = (u.get('name') or '').strip()
    for dom in u.get('domains') or []:
        dom = dom.strip().lower()
        if re.fullmatch(r'[a-z0-9.-]+\.[a-z]{2,}', dom) and dom not in seen and 2 <= len(name) <= 200:
            seen[dom] = (name, u.get('country'))
rows = [f"({q(k)},{q(v[0])},'college',{q(v[1])},'university_registry')" for k, v in sorted(seen.items())]
print("-- GENERATED by scripts/generate-university-domains.py (Hipo university-domains-list, MIT).")
for i in range(0, len(rows), 500):
    print("insert into public.org_domains (domain, org_name, kind, country, source) values")
    print(",\n".join(rows[i:i + 500]) + "\non conflict (domain) do nothing;")
